-- Схема базы данных «ПрактикаТрек» (PostgreSQL 15)
-- Соответствует диаграмме классов из ПР3 и ORM-моделям app/db/models.py.

CREATE TABLE groups (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    group_id      INTEGER REFERENCES groups (id),
    CONSTRAINT ck_users_role CHECK (role IN ('student', 'teacher'))
);

CREATE TABLE subjects (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200) NOT NULL,
    teacher_id INTEGER NOT NULL REFERENCES users (id),
    group_id   INTEGER NOT NULL REFERENCES groups (id)
);

CREATE TABLE assignments (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id  INTEGER NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    title       VARCHAR(200) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    deadline    DATE NOT NULL
);

CREATE TABLE submissions (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id INTEGER NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    student_id    INTEGER NOT NULL REFERENCES users (id),
    status        VARCHAR(20) NOT NULL DEFAULT 'not_started',
    comment       TEXT NOT NULL DEFAULT '',
    submitted_at  TIMESTAMP,
    CONSTRAINT uq_submission_assignment_student UNIQUE (assignment_id, student_id),
    CONSTRAINT ck_submissions_status CHECK (
        status IN ('not_started', 'in_progress', 'submitted', 'rework', 'accepted'))
);

-- Индексы под частые запросы (NFR-01)
CREATE INDEX ix_users_group_id ON users (group_id);
CREATE INDEX ix_subjects_teacher_id ON subjects (teacher_id);
CREATE INDEX ix_subjects_group_id ON subjects (group_id);
CREATE INDEX ix_assignments_subject_id ON assignments (subject_id);
CREATE INDEX ix_submissions_student_id ON submissions (student_id);
CREATE INDEX ix_submissions_assignment_id ON submissions (assignment_id);
