def evidence():
    data = json.loads((OUT / "evidence/results.json").read_text(encoding="utf-8"))
    cov = json.loads((OUT / "evidence/coverage.json").read_text(encoding="utf-8"))
    suite = ET.parse(OUT / "evidence/junit.xml").getroot()
    suites = [suite] if suite.tag == "testsuite" else list(suite)
    count = sum(int(s.get("tests", 0)) for s in suites)
    fail = sum(int(s.get("failures", 0)) + int(s.get("errors", 0)) for s in suites)
    skip = sum(int(s.get("skipped", 0)) for s in suites)
    percent = cov["totals"]["percent_covered"]
    summary = f"pytest: {count} тестов, ошибок/падений {fail}, пропусков {skip}; покрытие строк app: {percent:.1f}%."
    rows = [(k, "успешно" if v["exit_code"] == 0 else "есть замечания", v["command"])
            for k, v in data.items() if isinstance(v, dict)]
    return summary, table(["Проверка", "Результат", "Команда"], rows)


